export var PHOTO_ROLES = [
  'front_full', 'front_close',
  'rear_full', 'rear_close',
  'side_left_full', 'side_right_full', 'side_close',
  'roof_top',
  'interior_steering', 'interior_dashboard',
  'interior_seats_front', 'interior_seats_rear', 'interior_other',
  'engine_bay', 'frame_undercarriage', 'wheel_close',
  'vin_plate', 'odometer_screen', 'damage_marker',
  'unclear',
]

export function buildClassifyPrompt(photoCount) {
  var p = ''
  p += 'Ти класифікуєш ' + photoCount + ' фото з аукціону Copart/IAAI.\n'
  p += 'Для КОЖНОГО фото визнач його роль з фіксованого списку нижче.\n\n'

  p += 'РОЛІ (вибирай ТІЛЬКИ з цього списку):\n'
  PHOTO_ROLES.forEach(function(role) { p += '- ' + role + '\n' })

  p += '\nПОЯСНЕННЯ:\n'
  p += '- "front_full" — видно весь перед авто (фронтальний або ¾ ракурс спереду)\n'
  p += '- "front_close" — крупний план переду: фара, решітка, бампер як деталь\n'
  p += '- "rear_full" / "rear_close" — те саме для заду\n'
  p += '- "side_left_full" / "side_right_full" — водійський/пасажирський бік збоку\n'
  p += '- "side_close" — бічна деталь (двері крупно, дзеркало, поріг)\n'
  p += '- "roof_top" — дах згори\n'
  p += '- "interior_steering" — кермо ЗБЛИЗЬКА (з логотипом)\n'
  p += '- "interior_dashboard" — приладова панель/екран\n'
  p += '- "interior_seats_front" / "interior_seats_rear" — сидіння\n'
  p += '- "interior_other" — стеля, оббивка, інше всередині\n'
  p += '- "engine_bay" — відкритий моторний відсік\n'
  p += '- "frame_undercarriage" — днище, підвіска\n'
  p += '- "wheel_close" — колесо/тормоз\n'
  p += '- "vin_plate" — VIN табличка\n'
  p += '- "odometer_screen" — одометр\n'
  p += '- "damage_marker" — стрілка/marker з аукціону\n'
  p += '- "unclear" — мутне, темне, не зрозуміло\n\n'

  p += 'ОРІЄНТАЦІЯ side_left vs side_right:\n'
  p += '- ЛІВИЙ бік авто = водійський (авто ліворульне).\n'
  p += '- Профіль з водійськими дверима = side_left_full.\n'
  p += '- Профіль з пасажирськими дверима = side_right_full.\n\n'

  p += 'ВИВІД (ТІЛЬКИ JSON):\n'
  p += '{\n'
  p += '  "classifications": [\n'
  p += '    {"photo_index": 0, "role": "front_full", "confidence": 0.0-1.0},\n'
  p += '    ... (по одному на КОЖНЕ з ' + photoCount + ' фото)\n'
  p += '  ]\n'
  p += '}\n'

  return p
}

export function buildZoneGroupPrompt(opts) {
  var groupName = opts.groupName
  var photoCount = opts.photoCount
  var photoRoles = opts.photoRoles
  var reference = opts.reference
  var declared = opts.declared
  var secondary = opts.secondary
  var titleClass = opts.titleClass
  var titleType = opts.titleType
  var checkpoints = opts.checkpoints

  var p = ''

  p += 'Ти оцінюєш ' + reference.make + ' ' + reference.model
  if (reference.generation && reference.generation !== 'unknown') {
    p += ' (' + reference.generation + ', ' + reference.year_from + '-' + reference.year_to + ')'
  }
  p += '.\n\n'

  p += 'Тобі дано ' + photoCount + ' фото — ВСІ вони відносяться до зони "' + groupName + '".\n'
  p += 'Ти бачиш ці фото РАЗОМ — порівнюй між ними і cross-reference.\n\n'

  p += 'РОЛІ ФОТО (як я класифікував):\n'
  photoRoles.forEach(function(pr) {
    p += '- Фото ' + pr.index_in_batch + ': ' + pr.role + '\n'
  })

  p += '\nЗАДЕКЛАРОВАНО АУКЦІОНОМ:\n'
  p += '- Primary: ' + declared + '\n'
  if (secondary && secondary !== 'N/A' && secondary !== '-') {
    p += '- Secondary: ' + secondary + '\n'
  }
  if (titleType) p += '- Title Type: ' + titleType + '\n'

  if (titleClass === 'flood') {
    p += '\n!!! TITLE = FLOOD. Авто було у воді — шукай сліди води навіть якщо primary не водяний.\n'
  } else if (titleClass === 'salvage') {
    p += '\nTitle = SALVAGE — авто списане страховою.\n'
  } else if (titleClass === 'rebuilt') {
    p += '\nTitle = REBUILT — авто пройшло відновлення.\n'
  }

  if (reference.identification && Object.keys(reference.identification).length > 0) {
    p += '\nЯК МАЄ ВИГЛЯДАТИ ЦІЛЕ АВТО ЦІЄЇ МОДЕЛІ:\n'
    Object.keys(reference.identification).forEach(function(k) {
      p += '- ' + reference.identification[k] + '\n'
    })
  }

  p += '\n═══ КРИТИЧНО ВАЖЛИВО ПРО СТОРОНИ — ЧИТАЙ УВАЖНО ═══\n'
  p += 'Ти ЛЕГКО плутаєш "ліву" і "праву" сторону авто. Тому ми робимо так:\n\n'
  p += 'У відповідях ОПИСУЙ ПОЛОЖЕННЯ ВИКЛЮЧНО ВІДНОСНО ФОТО:\n'
  p += '  ✓ "зліва на фото" або "у лівій частині фото"\n'
  p += '  ✓ "справа на фото" або "у правій частині фото"\n'
  p += '  ✓ "по центру фото"\n'
  p += '  ✓ "знизу фото" / "зверху фото"\n\n'
  p += 'НЕ ПИШИ:\n'
  p += '  ✗ "водійська сторона" / "пасажирська сторона"\n'
  p += '  ✗ "лівий бік авто" / "правий бік авто"\n'
  p += '  ✗ "ліва фара" / "права фара" (просто "фара зліва на фото" або "фара справа на фото")\n\n'
  p += 'Чому: камера дзеркалить, ти плутаєшся. JS система отримає твою відповідь і САМА перекладе позицію на фото на сторону авто, бо вона знає роль фото (front/rear/side). Не намагайся це зробити сам.\n\n'

  p += '═══ ЗАВДАННЯ ═══\n'
  p += 'Я задам ' + checkpoints.flat.length + ' конкретних питань.\n'
  p += 'Для КОЖНОГО питання обери yes / no / unclear за ЧІТКИМИ ПРАВИЛАМИ нижче.\n\n'

  p += '═══ ПРАВИЛА ВІДПОВІДЕЙ — ЦЕ НАЙВАЖЛИВІШЕ ═══\n\n'

  p += '"yes" — коли ВСЕ ЦЕ правда:\n'
  p += '  ✓ Деталь чітко видно на хоча б одному фото\n'
  p += '  ✓ Деталь виглядає цілою (без видимих пошкоджень)\n'
  p += '  ✓ Ракурс достатній щоб переконатися\n'
  p += '  → НЕ ПИШИ unclear лише через "а раптом там щось не видно". Якщо деталь видно і вона ціла — це yes.\n\n'

  p += '"no" — коли є ВИДИМА ОЗНАКА ПОШКОДЖЕННЯ:\n'
  p += '  ✗ Рваний край пластику, прорив, видно внутрішні елементи\n'
  p += '  ✗ Тріщина, павутинка на склі/пластику\n'
  p += '  ✗ Деталь повністю відсутня (порожнє місце)\n'
  p += '  ✗ Складка, вмятина, нерівність на металі\n'
  p += '  ✗ Зміщення (зазор більший в одному місці ніж в іншому)\n'
  p += '  → ЯКЩО БАЧИШ хоча б одну з цих ознак — це "no". Не "unclear".\n'
  p += '  → НЕ сумнівайся "а раптом це нормально". Рваний бампер не нормальний.\n\n'

  p += '"unclear" — ТІЛЬКИ КОЛИ:\n'
  p += '  ? Деталь поза кадром (її просто не видно на жодному з даних фото)\n'
  p += '  ? Занадто далеко або мутно щоб розрізнити\n'
  p += '  ? Тінь/відблиск приховує саме цю частину\n'
  p += '  ? Бруд/налипання приховує саме цю частину\n'
  p += '  → unclear НЕ ОЗНАЧАЄ "не на 100% впевнений". Це означає "ракурс не дає побачити".\n'
  p += '  → Якщо деталь чітко видно — НЕ ПИШИ unclear, навіть якщо ти "обережний".\n\n'

  p += '═══ СПЕЦПРАВИЛО: ЕКРАНИ І ПРИЛАДОВІ ПАНЕЛІ ═══\n'
  p += 'Якщо приладова панель або центральний екран ВИМКНЕНІ (чорний без підсвітки) — це "unclear".\n'
  p += 'Не пиши "no" коли екран вимкнений. Тіні і відблиски на чорному екрані — НЕ попередження.\n'
  p += 'Тільки коли видно конкретний світний текст або символ warning — тоді "no".\n\n'

  p += '═══ НОМЕРИ ФОТО — НАДВАЖЛИВО ═══\n'
  p += 'Я дав тобі ' + photoCount + ' фото з номерами 0 до ' + (photoCount-1) + ' (це індекси в МОЄМУ батчі).\n'
  p += 'У evidence_photo і в полі "note" ВКАЗУЙ ТОЧНІ номери цих фото.\n'
  p += 'Якщо ознака на одному фото — один номер. Якщо на кількох — переліч ВСІ через кому.\n'
  p += 'НЕ пиши завжди "0" — використовуй РІЗНІ номери залежно від того яке фото показує ознаку.\n\n'

  p += '═══ ПРАВИЛО NOTE — ОБОВʼЯЗКОВЕ ДЛЯ "no" ═══\n'
  p += 'Кожна "no" відповідь МАЄ мати поле "note" що ПОЧИНАЄТЬСЯ з "Видно на фото X:" (або "Видно на фото X, Y:" якщо кілька).\n'
  p += 'note описує КОНКРЕТНО що ти бачиш — позиція ВІДНОСНО ФОТО (зліва/справа/центр), не "водійська/пасажирська".\n\n'
  p += 'Приклади ПРАВИЛЬНОГО note:\n'
  p += '- "Видно на фото 4: зліва на фото бампер має пробій, рваний пластик"\n'
  p += '- "Видно на фото 0, 4: справа на фото фара повністю відсутня, порожній отвір"\n'
  p += '- "Видно на фото 1: по центру фото на капоті складка біля решітки"\n\n'
  p += 'Приклади ПОГАНОГО note (НЕ ПИШИ):\n'
  p += '- "Бампер зліва (водійська сторона)" — НЕ роби висновок про сторону авто, лише про сторону фото\n'
  p += '- "Ліва фара пошкоджена" — пиши "фара зліва на фото пошкоджена" або "фара справа на фото пошкоджена"\n\n'

  p += '═══ ІНШІ ПРАВИЛА ═══\n'
  p += '1. Знято ≠ розбито. Розрізняй: "знятий і лежить поряд" / "відсутній" / "на місці але пробитий".\n'
  p += '2. Тіні і відблиски — НЕ пошкодження.\n'
  p += '3. Бруд і налипання — НЕ пошкодження.\n\n'

  p += '═══ ПИТАННЯ ═══\n\n'

  Object.keys(checkpoints.byZone).forEach(function(zid) {
    p += '── Зона: ' + zid + ' ──\n'
    checkpoints.byZone[zid].forEach(function(cp) {
      p += '\n• ' + cp.checkpoint_id + ':\n'
      p += '    Питання: ' + cp.question + '\n'
      p += '    "yes" коли: ' + cp.intact_signal + '\n'
      p += '    "no" коли:  ' + cp.damaged_signal + '\n'
    })
    p += '\n'
  })

  p += '═══ ВИВІД (ТІЛЬКИ JSON) ═══\n'
  p += '{\n'
  p += '  "checkpoints": [\n'
  p += '    {\n'
  p += '      "zone_id": "...",\n'
  p += '      "checkpoint_id": "...",\n'
  p += '      "answer": "yes" | "no" | "unclear",\n'
  p += '      "evidence_photo": число 0-' + (photoCount-1) + ' або null,\n'
  p += '      "note": "Видно на фото X: <позиція ВІДНОСНО ФОТО + опис>"\n'
  p += '    }\n'
  p += '  ],\n'
  p += '  "matches_declared": true | false,\n'
  p += '  "additional_observations": ["спостереження поза checkpoints"]\n'
  p += '}\n'

  return p
}